#!/usr/bin/env python3
"""Generates libs/text/text/wordfontlines.inc, the vertical metrics of the fonts a word processor's documents ask for.

Usage: gen_word_font_tables.py FONTNUMS_DIR OUT.inc

FONTNUMS_DIR holds one JSON file per font face (family, face, unitsPerEm, hhea and os2 tables' numbers), measured on a
Windows machine: numbers only, no font data. Each row of the output is a face: its family (lower case), its style
(0 regular, 1 bold, 2 italic, 3 bold italic), the units per em, the Windows ascent and descent, and the ascent,
descent, and line gap of the horizontal header, in font units. A font whose Windows height is over three ems (the math font's,
made for stacking formulas) isn't a line of text's: its horizontal header's ascent and descent stand for them."""
import glob, json, os, sys

STYLES = {"regular": 0, "bold": 1, "italic": 2, "bolditalic": 3}


def main():
    src, out = sys.argv[1], sys.argv[2]
    rows = []
    for path in sorted(glob.glob(os.path.join(src, "*.json"))):
        d = json.load(open(path, encoding="utf-8"))
        if d.get("face") not in STYLES:
            continue
        o, h = d["os2"], d["hhea"]
        win_ascent, win_descent = o["winAscent"], o["winDescent"]
        if win_ascent + win_descent > 3 * d["unitsPerEm"]:
            win_ascent, win_descent = h["ascender"], -h["descender"]
        rows.append((d["family"].lower(), STYLES[d["face"]], d["unitsPerEm"], win_ascent, win_descent, h["ascender"], -h["descender"], h["lineGap"]))
    rows.sort()
    with open(out, "w", encoding="utf-8", newline="\n") as f:
        f.write("// Generated by tools/gen_word_font_tables.py from font measurements (numbers only, no font data).\n")
        f.write("// Family (lower case), style (0 regular, 1 bold, 2 italic, 3 bold italic), units per em, Windows ascent and descent,\n")
        f.write("// then the horizontal header's ascent, descent (as a positive number), and line gap.\n")
        f.write("static const struct { const char *family; int style, upm, winAscent, winDescent, ascent, descent, gap; } kWordFontFaces[] = {\n")
        for r in rows:
            f.write('    {"%s", %d, %d, %d, %d, %d, %d, %d},\n' % r)
        f.write("};\n")
    print(len(rows), "faces")


main()
