ClipboardHistory *ClipboardHistory::instance()
{
    QCoreApplication *app = QCoreApplication::instance();
    if (!app) return nullptr;
    if (auto *h = app->findChild<ClipboardHistory *>(QString(), Qt::FindDirectChildrenOnly)) return h;
    return new ClipboardHistory(app);
}

ClipboardHistory::ClipboardHistory(QObject *parent) : QObject(parent)
{
    m_whenClosed = QSettings().value(QLatin1String(kSettingsKey), false).toBool();
    // The history ends with the program's last window.
    connect(qApp, &QGuiApplication::lastWindowClosed, this, [this] { clear(); });
    updateWatching();
}

bool ClipboardHistory::canCollectOtherPrograms()
{
#ifdef Q_OS_MACOS
    return false;   // (Qt gives no way to read the macOS hints that mark a secret, so what other programs copy is never kept there)
#else
    return true;
#endif
}

void ClipboardHistory::updateWatching()
{
    const bool want = collecting();
    if (want == m_watching) return;
    m_watching = want;
    if (QClipboard *cb = QGuiApplication::clipboard()) {
        if (want) connect(cb, &QClipboard::dataChanged, this, &ClipboardHistory::onClipboard);
        else disconnect(cb, &QClipboard::dataChanged, this, &ClipboardHistory::onClipboard);
    }
}

void ClipboardHistory::addOpenPane(int by)
{
    m_openPanes = std::max(0, m_openPanes + by);
    updateWatching();
}

void ClipboardHistory::setCollectWhenClosed(bool on)
{
    m_whenClosed = on;
    QSettings().setValue(QLatin1String(kSettingsKey), on);
    updateWatching();
}

void ClipboardHistory::setCollectOtherPrograms(bool on)
{
    m_others = on && canCollectOtherPrograms();
}

void ClipboardHistory::onClipboard()
{
    if (m_putting) return;
    QClipboard *cb = QGuiApplication::clipboard();
    if (m_put && cb->mimeData() == m_put.data()) return;   // (the notice of an item put back, which may come after putOnClipboard has returned)
    noteClipboard(cb->mimeData(), m_owns ? m_owns() : cb->ownsClipboard());
}

bool ClipboardHistory::isSecret(const QMimeData *mime)
{
    if (!mime) return false;
    return isSecretSource(MimeSource(mime, false));
}

void ClipboardHistory::startIfAsked()
{
    if (QSettings().value(QLatin1String(kSettingsKey), false).toBool()) instance();
}

void ClipboardHistory::setOwnStateHooks(const std::function<std::any(const QMimeData *)> &take, const std::function<void(const std::any &)> &give)
{
    g_takeOwnState = take;
    g_giveOwnState = give;
}

quint64 ClipboardHistory::noteClipboard(const QMimeData *mime, bool own)
{
    if (!mime || !collecting() || (!own && !m_others)) return 0;
    const quint64 id = noteSource(MimeSource(mime, own), own);
    if (id && own && g_takeOwnState)
        for (Item &it : m_items)
            if (it.id == id) it.ownState = g_takeOwnState(mime);
    return id;
}

quint64 ClipboardHistory::noteSource(const ClipboardSource &source, bool own)
{
    if (!collecting() || (!own && !m_others)) return 0;
    if (isSecretSource(source)) return 0;
    Item item;
    item.fromOtherProgram = !own;
    bool tooBig = false;
    const QStringList formats = source.formats();
    QImage preview;   // the picture the thumbnail is made from
    if (own) {
        // The forms the pane needs to put the copy back, each read within what is left of the 8 MB (a size known beforehand refuses a copy without reading it).
        qint64 bytes = 0;
        for (const QString &f : formsToKeep(formats)) {
            const qint64 offered = source.sizeOf(f);
            if (offered > kMostItemBytes - bytes) {
                tooBig = true;
                break;
            }
            bool over = false;
            const QByteArray data = source.read(f, kMostItemBytes - bytes, &over);
            if (over) {
                tooBig = true;
                break;
            }
            bytes += data.size();
            item.formats.append({f, data});
        }
        // The picture form is not what the pane pastes from when the copy has forms of its own: it counts only while it fits, and only a small preview is kept when it does not.
        const QImage picture = tooBig ? QImage() : source.ownImage();
        if (!picture.isNull()) {
            const qint64 pictureBytes = picture.sizeInBytes();
            if (bytes + pictureBytes <= kMostItemBytes) {
                item.picture = picture;
                bytes += pictureBytes;
            } else if (item.formats.isEmpty()) {
                tooBig = true;
            } else {
                preview = picture;
            }
        }
        item.bytes = bytes;
    } else {
        // One form at most: the plain text when the offer has text, else one picture form. The platform reads a form whole, so a second form would double what is read.
        // An offer already refused (the same identity, where the platform gives one) or being read right now is not read again.
        const quint64 identity = source.identity();
        if (m_fetching || (identity != 0 && identity == m_refusedIdentity)) return 0;
        struct Fetching {
            bool &flag;
            explicit Fetching(bool &f) : flag(f) { flag = true; }
            ~Fetching() { flag = false; }
        } fetching(m_fetching);
        const QString plain = QStringLiteral("text/plain");
        if (formats.contains(plain)) {
            const qint64 offered = source.sizeOf(plain);
            bool over = false;
            const QByteArray text = offered > kMostItemBytes ? QByteArray() : source.read(plain, kMostItemBytes, &over);
            if (offered > kMostItemBytes || over) tooBig = true;
            else if (!text.isEmpty()) {
                item.formats.append({plain, text});
                item.bytes += text.size();
            }
        } else {
            item.picture = otherProgramPicture(source, formats, kMostItemBytes, &tooBig);
            item.bytes += item.picture.sizeInBytes();
        }
        if (tooBig) m_refusedIdentity = identity;
    }
    if (tooBig) {
        ++m_tooLarge;
        Q_EMIT tooLarge();
        return 0;
    }
    if (item.formats.isEmpty() && item.picture.isNull()) return 0;
    // What it is.
    bool hasText = false, hasHtml = false, rich = false;
    item.kind = Kind::Other;
    for (const auto &f : item.formats) {
        if (f.first == QLatin1String(kSlidesForm)) item.kind = Kind::Slides;
        else if (f.first == QLatin1String(kCellsForm) && item.kind != Kind::Slides) item.kind = Kind::Cells;
        else if (f.first == QLatin1String(kShapesForm) && item.kind != Kind::Slides && item.kind != Kind::Cells) item.kind = Kind::Shapes;
        if (f.first == QLatin1String("text/plain")) hasText = true;
        if (f.first == QLatin1String("text/html") || f.first == QLatin1String("application/x-jeffpub-text") || f.first.contains(QLatin1String("rtf"))) hasHtml = true;
        if (f.first == QLatin1String("application/x-jeffwrite-fragment")) rich = true;
    }
    if (item.kind == Kind::Other) {
        if (hasHtml || rich) item.kind = Kind::FormattedText;
        else if (hasText) item.kind = Kind::Text;
        else if (!item.picture.isNull()) item.kind = Kind::Picture;
    }
    for (const auto &f : item.formats)
        if (f.first == QLatin1String("text/plain")) item.preview = QString::fromUtf8(f.second.left(1000)).left(200);
    item.thumbnail = thumbnailOf(item.picture.isNull() ? preview : item.picture);
    // The same as one kept already: kept once, and brought to the front.
    for (int i = 0; i < m_items.size(); ++i)
        if (m_items.at(i).formats == item.formats && m_items.at(i).picture == item.picture) {
            if (i == 0) return 0;
            m_items.move(i, 0);
            Q_EMIT changed();
            return m_items.first().id;
        }
    item.id = ++m_lastId;
    m_items.prepend(item);
    m_total += item.bytes;
    while (m_items.size() > kMostItems) {
        m_total -= m_items.last().bytes;
        m_items.removeLast();
    }
    while (m_total > kMostTotalBytes && m_items.size() > 1) {
        m_total -= m_items.last().bytes;
        m_items.removeLast();
        ++m_dropped;
    }
    Q_EMIT changed();
    return item.id;
}

QMimeData *ClipboardHistory::mimeOf(quint64 id) const
{
    for (const Item &it : m_items) {
        if (it.id != id) continue;
        auto *md = new QMimeData;
        for (const auto &f : it.formats) md->setData(f.first, f.second);
        if (!it.picture.isNull()) md->setImageData(it.picture);
        return md;
    }
    return nullptr;
}

bool ClipboardHistory::putOnClipboard(quint64 id)
{
    QMimeData *md = mimeOf(id);
    if (!md) return false;
    for (const Item &it : m_items)
        if (it.id == id && it.ownState.has_value() && g_giveOwnState) g_giveOwnState(it.ownState);
    m_put = md;
    m_putting = true;
    QGuiApplication::clipboard()->setMimeData(md);
    m_putting = false;
    return true;
}

void ClipboardHistory::remove(quint64 id)
{
    for (int i = 0; i < m_items.size(); ++i)
        if (m_items.at(i).id == id) {
            m_total -= m_items.at(i).bytes;
            m_items.removeAt(i);
            Q_EMIT changed();
            return;
        }
}

void ClipboardHistory::clear()
{
    if (m_items.isEmpty()) return;
    m_items.clear();
    m_total = 0;
    Q_EMIT changed();
}

